import SwiftUI
import SwiftData
import CircadianKit

@main
struct CircadiaApp: App {

    /// One on-disk store for the whole app. Trips persist, so the plan you built on the
    /// sofa last Tuesday is the same plan your phone notifies you about at 06:40.
    let container: ModelContainer

    @State private var scheduler = NotificationScheduler()

    init() {
        do {
            container = try ModelContainer(for: StoredTrip.self)
        } catch {
            // A corrupt store should not brick the app; fall back to memory and say so.
            container = try! ModelContainer(
                for: StoredTrip.self,
                configurations: ModelConfiguration(isStoredInMemoryOnly: true)
            )
        }
    }

    var body: some Scene {
        WindowGroup {
            #if DEBUG
            // `-demoScreen <name>` boots straight into one screen with seeded data, so the
            // README screenshots can be regenerated by a script rather than assembled by
            // hand. See tools/screenshots.sh.
            if let screen = DemoScreen.fromLaunchArguments() {
                DemoScreenHost(screen: screen)
                    .environment(scheduler)
            } else {
                TripListView()
                    .environment(scheduler)
            }
            #else
            TripListView()
                .environment(scheduler)
            #endif
        }
        .modelContainer(container)
        #if os(macOS)
        .defaultSize(width: 1000, height: 760)
        .windowToolbarStyle(.unified)
        #endif

        #if os(macOS)
        Settings {
            SettingsView()
                .environment(scheduler)
        }
        #endif
    }
}
